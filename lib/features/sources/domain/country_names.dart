class CountryNames {
  /// Returns the readable country name for a code, or null if unknown.
  /// Tries the code as-is first, then maps alpha-3 (FIN, DEU, …) to
  /// alpha-2 (FI, DE, …) and looks it up again.
  static String? lookup(String code, {required String locale}) {
    final upper = code.toUpperCase();
    final map = locale.startsWith('tr') ? _tr : _en;
    final direct = map[upper];
    if (direct != null) return direct;
    final aliased = _alpha3to2[upper];
    if (aliased != null) return map[aliased];
    return null;
  }

  /// Readable name, or the original code if no mapping is known.
  static String forCode(String code, {required String locale}) {
    return lookup(code, locale: locale) ?? code.toUpperCase();
  }

  /// "Turkey - TR" / "Finland - FIN" / "EXYU" (unknown).
  /// When the code itself is what we'd display (no mapping), drop the
  /// trailing " - CODE" suffix to avoid duplication.
  static String labelWithCode(String code, {required String locale}) {
    final upper = code.toUpperCase();
    final name = lookup(upper, locale: locale);
    if (name == null) return upper;
    return '$name - $upper';
  }

